"""Turn the JSON schema in a vision_prompt.json into a GBNF grammar for llama.cpp on the phone.

llama.cpp b12606 no longer ships the Python json_schema_to_grammar.py, and the phone only gets
llama.h (llama_sampler_init_grammar takes GBNF text). This handles the subset the foraging schema
uses: object (every property required, emitted in schema order), string, string enum, number with
minimum 0 / maximum 1, and array with minItems / maxItems.

Usage: python3 -I scripts/schema_to_gbnf.py datasets/phone/foraging/vision_prompt.json \
           datasets/phone/foraging/vision_prompt.gbnf
"""
import json
import re
import sys

MAX_STRING_CHARS = 600   # observations are "at most 80 words"; this stops a runaway string


class Gen:
    def __init__(self):
        self.rules = {}

    def add(self, name, body):
        name = re.sub(r"[^a-zA-Z0-9-]", "-", name)
        if name in self.rules and self.rules[name] != body:
            i = 2
            while f"{name}-{i}" in self.rules:
                i += 1
            name = f"{name}-{i}"
        self.rules[name] = body
        return name

    def visit(self, s, name):
        t = s.get("type")
        if "enum" in s:
            alts = " | ".join(json.dumps(json.dumps(v)) for v in s["enum"])
            return self.add(name, alts)
        if t == "string":
            return "string"
        if t == "number":
            if s.get("minimum") == 0 and s.get("maximum") == 1:
                return "unit-number"
            raise SystemExit(f"{name}: only numbers in [0, 1] are supported")
        if t == "array":
            item = self.visit(s["items"], f"{name}-item")
            lo, hi = s.get("minItems", 0), s.get("maxItems")
            if hi is None or lo < 0 or hi < max(lo, 1):
                raise SystemExit(f"{name}: arrays need minItems >= 0 and maxItems >= max(minItems, 1)")
            first = f"{item} ws " + (f'("," ws {item} ws){{{max(lo, 1) - 1},{hi - 1}}}')
            if lo == 0:  # an empty list is allowed too
                first = f"({first})?"
            return self.add(name, f'"[" ws {first} "]"')
        if t == "object":
            props = s["properties"]
            missing = set(props) - set(s.get("required", []))
            if missing:
                raise SystemExit(f"{name}: optional properties not supported: {sorted(missing)}")
            parts = []
            for i, (k, v) in enumerate(props.items()):
                sep = "" if i == 0 else '"," ws '
                parts.append(f'{sep}{json.dumps(json.dumps(k))} ws ":" ws {self.visit(v, f"{name}-{k}")} ws')
            return self.add(name, '"{" ws ' + " ".join(parts) + ' "}"')
        raise SystemExit(f"{name}: unsupported schema {s}")


def main(src, dst):
    schema = json.load(open(src))["json_schema"]
    g = Gen()
    root = g.visit(schema, "root-obj")
    out = [f"# Generated by scripts/schema_to_gbnf.py from {src}. Do not edit by hand.",
           f"root ::= {root}"]
    out += [f"{k} ::= {v}" for k, v in g.rules.items()]
    out += [
        f'string ::= "\\"" char{{0,{MAX_STRING_CHARS}}} "\\""',
        'char ::= [^"\\\\\\x00-\\x1f] | "\\\\" ["\\\\/bfnrt]',
        'unit-number ::= "0" ("." [0-9]{1,3})? | "1" (".0" "0"{0,2})?',
        "ws ::= [ \\t\\n]{0,16}",
    ]
    open(dst, "w").write("\n".join(out) + "\n")
    print(f"wrote {dst} ({len(g.rules)} rules)")


if __name__ == "__main__":
    main(*sys.argv[1:3])
