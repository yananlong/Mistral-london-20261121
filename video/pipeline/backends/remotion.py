"""Remotion backend (kind="scene").

Per run, a fresh studio project is materialised at runs/<id>/studio from
video/studio/template, sharing one installed node_modules at video/studio
(symlinked in). Generator agents write one scene component per shot
(src/scenes/<shot>.<variant>.tsx); this backend registers a preview
composition per candidate and renders a still (or short mp4) for the
curator. The editor writes the single `main` composition and renders the
final mp4 with `npx remotion render`.

Requires: node >= 18, `npm install` once in video/studio, and a headless
browser (`npx remotion browser ensure` once). Set backends.remotion.render
to false to only generate code (offline scaffold test).
"""
from __future__ import annotations

import json
import re
import shutil
import subprocess
import time
from pathlib import Path

from ..config import VIDEO_ROOT
from ..media import probe_video
from ..schemas import ClipCandidate, EDL, ShotSpec
from .base import VideoBackend

STUDIO_ROOT = VIDEO_ROOT / "studio"
TEMPLATE = VIDEO_ROOT / "studio" / "template"


def _sanitize(s: str) -> str:
    return re.sub(r"[^a-zA-Z0-9_]", "_", s)


def _comp_id(s: str) -> str:
    """Remotion composition ids may only contain a-z, A-Z, 0-9, CJK and '-'."""
    return re.sub(r"[^a-zA-Z0-9-]", "-", s)


def _remotion_bin(studio: Path) -> list[str]:
    local = (Path(studio).absolute() / "node_modules" / ".bin" / "remotion")
    if local.exists():
        return [str(local)]
    return ["npx", "remotion"]


def _run(cmd: list[str], cwd: Path, timeout: int = 1800) -> subprocess.CompletedProcess:
    proc = subprocess.run(cmd, cwd=str(cwd), capture_output=True, text=True, timeout=timeout)
    if proc.returncode != 0:
        raise RuntimeError(
            f"remotion command failed in {cwd}: {' '.join(cmd)}\n{proc.stderr[-2500:]}"
        )
    return proc


class RemotionBackend(VideoBackend):
    name = "remotion"
    kind = "scene"

    # -- studio scaffolding -------------------------------------------------
    def prepare_studio(self, run_dir: Path, config: dict) -> Path:
        studio = run_dir / "studio"
        if (studio / "src").exists():
            return studio
        shutil.copytree(TEMPLATE / "src", studio / "src")
        for f in ("package.json", "tsconfig.json"):
            shutil.copy2(STUDIO_ROOT / f, studio / f)
        shared_nm = STUDIO_ROOT / "node_modules"
        if shared_nm.exists():
            link = studio / "node_modules"
            if not link.exists():
                link.symlink_to(shared_nm)
        else:
            raise RuntimeError(
                "video/studio/node_modules is missing — run `npm install` in video/studio first"
            )
        return studio

    def _manifest_path(self, studio: Path) -> Path:
        return studio / "src" / "scenes" / "manifest.json"

    def write_scene(self, studio: Path, shot: ShotSpec, variant_name: str, code: str,
                    video_cfg: dict) -> Path:
        scenes = studio / "src" / "scenes"
        scenes.mkdir(parents=True, exist_ok=True)
        path = scenes / f"{shot.id}.{_sanitize(variant_name)}.tsx"
        path.write_text(code)
        manifest = {}
        mp = self._manifest_path(studio)
        if mp.exists():
            manifest = json.loads(mp.read_text())
        manifest[path.name] = {
            "shot_id": shot.id,
            "variant": variant_name,
            "duration_s": shot.duration_s,
            "beat": shot.beat,
        }
        mp.write_text(json.dumps(manifest, indent=2))
        self._rewrite_candidates(studio, video_cfg)
        return path

    def _rewrite_candidates(self, studio: Path, video_cfg: dict) -> None:
        """Regenerate src/gen/candidates.tsx with one preview composition per scene."""
        mp = self._manifest_path(studio)
        manifest = json.loads(mp.read_text()) if mp.exists() else {}
        w, h, fps = int(video_cfg["width"]), int(video_cfg["height"]), int(video_cfg["fps"])
        lines = [
            "// AUTO-GENERATED by video/pipeline/backends/remotion.py — do not edit.",
            "import {Composition} from 'remotion';",
            "import type {ComponentType} from 'react';",
            "",
        ]
        entries = []
        for fname in sorted(manifest):
            info = manifest[fname]
            mod = fname[:-4]  # strip .tsx
            comp_id = f"cand-{_comp_id(info['shot_id'])}-{_comp_id(info['variant'])}"
            lines.append(f"import {{Scene as Scene_{_sanitize(mod)}}} from '../scenes/{mod}';")
            dur_frames = max(1, round(info["duration_s"] * fps))
            entries.append(
                f"  {{id: {json.dumps(comp_id)}, component: Scene_{_sanitize(mod)}, "
                f"durationInFrames: {dur_frames}, fps: {fps}, width: {w}, height: {h}}},"
            )
        lines.append("export const candidateComps = [")
        lines.extend(entries)
        lines.append("];")
        lines.append("export const CandidateCompositions = () => (")
        lines.append("  <>")
        lines.append("    {candidateComps.map((c) => (")
        lines.append("      <Composition key={c.id} id={c.id} component={c.component}")
        lines.append("        durationInFrames={c.durationInFrames} fps={c.fps}")
        lines.append("        width={c.width} height={c.height} />")
        lines.append("    ))}")
        lines.append("  </>")
        lines.append(");")
        gen = studio / "src" / "gen"
        gen.mkdir(exist_ok=True)
        (gen / "candidates.tsx").write_text("\n".join(lines) + "\n")

    # -- per-candidate generation + preview ---------------------------------
    def generate(self, shot: ShotSpec, variant: dict, out_dir: Path, ctx,
                 code: str | None = None, prompt: str = "") -> ClipCandidate:
        if not code:
            raise RuntimeError("remotion backend needs scene code from the generator agent")
        video = ctx.config["video"]
        studio = self.prepare_studio(ctx.run_dir, ctx.config)
        vname = variant["name"]
        scene_path = self.write_scene(studio, shot, vname, code, video)
        comp_id = f"cand-{_comp_id(shot.id)}-{_comp_id(vname)}"
        out_dir.mkdir(parents=True, exist_ok=True)
        preview = ""
        file = ""
        mode = self.cfg.get("preview_mode", "still")
        t0 = time.monotonic()
        if self.cfg.get("render", True) and mode != "none":
            mid_frame = max(0, round(shot.duration_s * int(video["fps"]) / 2))
            if mode == "still":
                png = out_dir / f"{shot.id}.{vname}.png"
                _run([*_remotion_bin(studio), "still", comp_id, str(png), "--frame", str(mid_frame)], studio)
                preview = str(png)
            else:  # short preview mp4 of the scene alone
                mp4 = out_dir / f"{shot.id}.{vname}.mp4"
                _run([*_remotion_bin(studio), "render", comp_id, str(mp4),
                      "--codec", "h264", "--crf", "28"], studio)
                file = str(mp4)
        wall = time.monotonic() - t0
        p = probe_video(file) if file else {"duration_s": shot.duration_s, "width": int(video["width"]),
                                            "height": int(video["height"]), "bytes": 0}
        return ClipCandidate(
            shot_id=shot.id,
            variant=vname,
            backend=self.name,
            model=variant.get("model", "remotion-scene"),
            prompt_used=prompt,
            file=file or str(scene_path.relative_to(studio)),
            poster=preview,
            preview=preview,
            duration_s=p["duration_s"],
            width=p["width"],
            height=p["height"],
            bytes=p.get("bytes", 0),
            generation_seconds=wall,
            cost_credits=0.0,
        )

    # -- final assembly ------------------------------------------------------
    def write_main(self, run_dir: Path, config: dict, winners: list[ClipCandidate],
                   edl: EDL) -> Path:
        """Write src/gen/main.tsx: one Sequence per winning shot inside Series."""
        video = config["video"]
        w, h, fps = int(video["width"]), int(video["height"]), int(video["fps"])
        studio = self.prepare_studio(run_dir, config)
        by_shot: dict[str, str] = {}
        for c in winners:
            by_shot[c.shot_id] = Path(c.file).name[:-4]  # scene module name
        lines = [
            "// AUTO-GENERATED by the editor agent — the final timeline.",
            "import {AbsoluteFill, Series, useVideoConfig} from 'remotion';",
        ]
        for e in edl.entries:
            mod = by_shot[e.shot_id]
            lines.append(f"import {{Scene as Scene_{_sanitize(mod)}}} from '../scenes/{mod}';")
        total_frames = sum(max(1, round(e.duration_s * fps)) for e in edl.entries)
        lines.append("")
        lines.append("export const Main = () => {")
        lines.append("  const {fps, width, height} = useVideoConfig();")
        lines.append("  return (")
        lines.append("    <AbsoluteFill style={{backgroundColor: '#000'}}>")
        lines.append("      <Series>")
        for e in edl.entries:
            mod = by_shot[e.shot_id]
            frames = max(1, round(e.duration_s * fps))
            lines.append(f"        <Series.Sequence durationInFrames={{{frames}}}>")
            lines.append(f"          <Scene_{_sanitize(mod)} />")
            lines.append(f"        </Series.Sequence>")
        lines.append("      </Series>")
        lines.append("    </AbsoluteFill>")
        lines.append("  );")
        lines.append("};")
        lines.append("")
        lines.append("export const mainMeta = {")
        lines.append(f"  durationInFrames: {total_frames},")
        lines.append(f"  fps: {fps},")
        lines.append(f"  width: {w},")
        lines.append(f"  height: {h},")
        lines.append("};")
        gen = studio / "src" / "gen"
        gen.mkdir(exist_ok=True)
        (gen / "main.tsx").write_text("\n".join(lines) + "\n")
        return studio

    def render_main(self, run_dir: Path, config: dict, out_mp4: Path) -> Path:
        studio = self.prepare_studio(run_dir, config)
        crf = str(self.cfg.get("crf", 20))
        conc = str(config.get("concurrency", 4))
        _run([*_remotion_bin(studio), "render", "main", str(out_mp4),
              "--codec", "h264", "--crf", crf, "--concurrency", conc,
              "--pixel-format", "yuv420p"], studio)
        return out_mp4
